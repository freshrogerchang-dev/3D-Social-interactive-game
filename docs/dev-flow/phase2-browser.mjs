// 原始碼整合檢查：只在測試路由的轉譯程式暴露相機，正式產品沒有測試探針。
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const { chromium } = require(path.join(process.env.PLAYWRIGHT_MODULE_DIR, 'playwright-core'));
const out = process.argv[2] || 'docs/dev-flow/phase2-evidence';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE_PATH, headless: true, args: ['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const checks = []; const errors = [];
const check = (name, pass, evidence) => { checks.push({ name, pass, evidence }); console.log(`${pass ? 'PASS' : 'FAIL'} ${name}`); };
try {
 const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
 await context.route('**/*', async route => {
  const url = new URL(route.request().url());
  if (url.pathname === '/') {
   let html = await readFile('index.html', 'utf8');
   html = html.replace('</head>', '<link rel="stylesheet" href="/src/styles.css"><script type="importmap">{"imports":{"three":"/three/three.module.js"}}</script></head>');
   return route.fulfill({ contentType: 'text/html', body: html });
  }
  if (url.pathname.startsWith('/three/')) return route.fulfill({ contentType: 'text/javascript', body: await readFile(path.join('node_modules/three/build', path.basename(url.pathname))) });
  const relative = url.pathname.slice(1);
  if (!relative.startsWith('src/')) return route.abort();
  if (relative.endsWith('.css')) return route.fulfill({ contentType: 'text/css', body: await readFile(relative) });
  const file = relative.endsWith('.ts') ? relative : relative + '.ts';
  let source = await readFile(file, 'utf8');
  if (file === 'src/main.ts') source = source.replace("import './styles.css';", '');
  if (file === 'src/input/FirstPersonController.ts') source = source.replace('this.syncCamera();', 'window.__p2 = { camera: this.camera, controller: this }; this.syncCamera();');
  const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
  return route.fulfill({ contentType: 'text/javascript', body: compiled });
 });
 const page = await context.newPage();
 page.on('pageerror', e => errors.push(String(e)));
 await page.goto('http://phase2.local/', { waitUntil: 'networkidle' });
 await page.waitForFunction(() => window.__p2 && document.querySelector('#overlay').hidden);
 const pose = () => page.evaluate(() => ({ x: window.__p2.camera.position.x, z: window.__p2.camera.position.z, y: window.__p2.camera.position.y, yaw: window.__p2.camera.rotation.y, fov: window.__p2.camera.fov }));
 const start = await pose();
 await page.locator('canvas').focus(); await page.keyboard.down('w'); await page.waitForFunction(z => window.__p2.camera.position.z < z - .15, start.z); await page.keyboard.up('w'); await page.waitForTimeout(300);
 const moved = await pose();
 check('WASD 前進、固定高度、保守速度', moved.z < start.z - .1 && moved.z > start.z - 1 && moved.y === start.y, { start, moved });
 await page.getByRole('button', { name: '暫停', exact: true }).click();
 const paused = await pose(); await page.waitForTimeout(300);
 check('暫停相機完全停住', JSON.stringify(paused) === JSON.stringify(await pose()));
 await page.getByRole('button', { name: '繼續', exact: true }).click(); await page.waitForTimeout(300);
 check('恢復不沿用按鍵或殘留速度', JSON.stringify(paused) === JSON.stringify(await pose()));
 await page.getByRole('button', { name: '返回安全區', exact: true }).click();
 const safe = await pose();
 check('返回安全區恢復位置並保持暫停', safe.x === start.x && safe.z === start.z && await page.getByRole('heading', { name: '已返回安全區' }).isVisible(), safe);
 await page.getByRole('button', { name: '繼續', exact: true }).click();
 await page.locator('canvas').tap({ position: { x: 195, y: 550 } }); await page.waitForTimeout(600);
 const tapped = await pose();
 check('手機點地面前往，不自動轉向', tapped.z < safe.z - .1 && tapped.yaw === safe.yaw, tapped);
 await page.evaluate(() => window.dispatchEvent(new Event('blur'))); const blurred = await pose(); await page.waitForTimeout(300);
 check('失焦丟棄前往目標與速度', JSON.stringify(blurred) === JSON.stringify(await pose()));
 await page.mouse.move(190, 420); await page.mouse.down(); await page.mouse.move(260, 440, { steps: 8 }); await page.mouse.up(); await page.waitForTimeout(150);
 const turned = await pose();
 check('拖曳轉向，拖曳不觸發移動', Math.abs(turned.yaw - blurred.yaw) > .02 && turned.x === blurred.x && turned.z === blurred.z, turned);
 await page.locator('canvas').dispatchEvent('pointercancel'); const cancelled = await pose(); await page.waitForTimeout(200);
 check('pointercancel 清空輸入', JSON.stringify(cancelled) === JSON.stringify(await pose()));
 await page.locator('canvas').focus(); await page.keyboard.down('d'); await page.waitForTimeout(100);
 await page.getByRole('button', { name: '暫停', exact: true }).focus(); const uiPose = await pose(); await page.waitForTimeout(250); await page.keyboard.up('d');
 check('UI 聚焦不繼續移動', JSON.stringify(uiPose) === JSON.stringify(await pose()));
 await page.getByRole('button', { name: '暫停', exact: true }).focus(); const e = await page.evaluate(() => { const e = new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true, cancelable: true }); document.activeElement.dispatchEvent(e); return e.defaultPrevented; });
 check('UI 方向鍵不被控制器攔截', !e);
 await page.getByText('操作與設定', { exact: true }).click();
 await page.getByRole('button', { name: '往前一步', exact: true }).click(); await page.waitForFunction(p => Math.hypot(window.__p2.camera.position.x - p.x, window.__p2.camera.position.z - p.z) > .15, uiPose);
 const stepped = await pose();
 check('按鈕導覽可單次點按移動', Math.hypot(stepped.x - uiPose.x, stepped.z - uiPose.z) > .1);
 await page.getByRole('button', { name: '停止移動', exact: true }).click(); const stopped = await pose(); await page.waitForTimeout(250);
 check('停止移動清目標與速度', JSON.stringify(stopped) === JSON.stringify(await pose()));
 await page.locator('input[name=fov]').fill('75'); await page.locator('input[name=fov]').dispatchEvent('input');
 check('視野可調整且有範圍', (await pose()).fov === 75);
 const settingsBefore = await pose(); await page.keyboard.press('ArrowLeft'); await page.waitForTimeout(100);
 check('設定滑桿聚焦不觸發方向鍵移動', (await pose()).x === settingsBefore.x && (await pose()).z === settingsBefore.z);
 await page.getByRole('button', { name: '暫停', exact: true }).click();
 check('暫停收起操作區，安全按鈕仍可用', !(await page.locator('#movement-controls').isVisible()) && await page.getByRole('button', { name: '返回安全區', exact: true }).isVisible());
 await page.getByRole('button', { name: '結束本次', exact: true }).click(); await page.getByRole('button', { name: '重新開始', exact: true }).click();
 await page.waitForFunction(() => document.querySelector('#overlay').hidden);
 check('重啟保留已選視野，只有一個場景', (await pose()).fov >= 50 && await page.locator('canvas').count() === 1);
 // 真正的 CDP 觸控點，有效 pointer capture；不是人工 PointerEvent。
 const cdp = await context.newCDPSession(page);
 await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 });
 await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x:180,y:430,id:1 },{ x:220,y:430,id:2 }] });
 await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x:170,y:430,id:1 },{ x:230,y:430,id:2 }] });
 await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
 const multitouch = await pose(); await page.waitForTimeout(300);
 check('多指不產生前往或轉向', JSON.stringify(multitouch) === JSON.stringify(await pose()));
 if (!(await page.locator('#movement-controls').evaluate(el => el.open))) await page.getByText('操作與設定', { exact: true }).click();
 await page.locator('#movement-controls').evaluate(el => el.scrollTop = 0);
 await page.screenshot({ path: path.join(out, 'phone-controls.png') });
 await page.setViewportSize({ width: 320, height: 360 });
 await page.addStyleTag({ content: ':root { font-size: 32px; }' });
 await page.getByRole('button', { name: '往前一步', exact: true }).click();
 await page.getByRole('button', { name: '停止移動', exact: true }).click();
 check('短畫面大字：導覽按鈕可捲動到並點按', true);
 await page.screenshot({ path: path.join(out, 'large-text-controls.png') });
 check('沒有未處理例外', errors.length === 0, errors);
 await context.close();
} finally { await browser.close(); }
await writeFile(path.join(out,'integration.json'), JSON.stringify({ node: process.version, sourceProbe: true, checks, errors }, null, 2) + '\n');
console.log(`${checks.filter(c => c.pass).length}/${checks.length} passed`);
process.exitCode = checks.every(c => c.pass) ? 0 : 1;
