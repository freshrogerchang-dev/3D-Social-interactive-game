/** 詞語讀音優先於單字，用於疊字後字輕聲等依上下文變化的讀音。 */
export const PHRASE_READINGS: Readonly<Record<string, readonly string[]>> = {
  媽媽: ['ㄇㄚ', '˙ㄇㄚ'],
  謝謝: ['ㄒㄧㄝˋ', '˙ㄒㄧㄝ'],
};

/** 逐字回傳讀音（詞語優先、再查單字），沒有讀音的字回傳 null。 */
export function readingsOf(text: string): (string | null)[] {
  const characters = Array.from(text);
  const result: (string | null)[] = [];
  for (let index = 0; index < characters.length;) {
    const phrase = Object.entries(PHRASE_READINGS).find(
      ([word]) => characters.slice(index, index + Array.from(word).length).join('') === word,
    );
    if (phrase) {
      result.push(...phrase[1]);
      index += phrase[1].length;
    } else {
      result.push(READINGS[characters[index] ?? ''] ?? null);
      index += 1;
    }
  }
  return result;
}

export function annotatedText(text: string): DocumentFragment {
  const fragment = document.createDocumentFragment();
  const readings = readingsOf(text);
  Array.from(text).forEach((character, index) => {
    const reading = readings[index];
    if (!reading) {
      fragment.append(character);
      return;
    }
    const ruby = document.createElement('ruby');
    const base = document.createElement('span');
    base.className = 'ruby-character';
    base.textContent = character;
    ruby.append(base);
    const rt = document.createElement('rt');
    const neutral = reading.startsWith('˙');
    const tone = neutral ? '˙' : reading.match(/[ˊˇˋ]$/u)?.[0];
    const symbols = document.createElement('span');
    symbols.className = 'zhuyin-symbols';
    symbols.textContent = reading.replace(/[˙ˊˇˋ]/gu, '');
    rt.append(symbols);
    if (tone) {
      const mark = document.createElement('span');
      mark.className = neutral ? 'zhuyin-neutral' : 'zhuyin-tone';
      mark.textContent = tone;
      rt.append(mark);
      if (neutral) rt.classList.add('has-neutral');
    }
    rt.setAttribute('aria-hidden', 'true');
    ruby.append(rt);
    fragment.append(ruby);
  });
  return fragment;
}
